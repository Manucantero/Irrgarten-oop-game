    @Override
    public void showGame(GameState gameState) {
        this.Laberinto.setText(gameState.getLabyrinth());
        this.Players.setText(gameState.getPlayers());
        this.Monsters.setText(gameState.getMonsters());
        this.log.setText(gameState.getLog());
        this.j_actual.setText("Player#" + 
                        Integer.toString(gameState.getCurrentPlayer()) + " moves");
        
        if(gameState.isWinner()){
            this.Ganador.setText("Player#" + 
                        Integer.toString(gameState.getCurrentPlayer()) + " WON");
            this.Ganador.setVisible(true);
            
        }
        repaint();
    }
    
